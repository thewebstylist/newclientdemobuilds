// Bundles everything in public/ into one self-contained Worker: dist/worker.js
// Usage: node tools/build.mjs
import { readFileSync, writeFileSync, readdirSync, statSync, mkdirSync } from "node:fs";
import { join, relative, extname, dirname } from "node:path";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";

// Minify CSS/JS with esbuild when installed (npm i), and strip HTML indentation.
let esbuild = null;
try { esbuild = await import("esbuild"); } catch { console.warn("esbuild not installed: assets are bundled unminified"); }
const minify = async (body, ext) => {
  if (ext === ".html") return body.replace(/\n\s+/g, "\n");
  if (esbuild && (ext === ".css" || ext === ".js")) return (await esbuild.transform(body, { loader: ext.slice(1), minify: true })).code;
  return body;
};

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const pub = join(root, "public");
const TYPES = { ".html": "text/html; charset=utf-8", ".css": "text/css; charset=utf-8", ".js": "text/javascript; charset=utf-8", ".svg": "image/svg+xml", ".json": "application/json", ".txt": "text/plain; charset=utf-8", ".xml": "application/xml" };
const BINARY = { ".jpg": "image/jpeg", ".jpeg": "image/jpeg", ".png": "image/png", ".webp": "image/webp", ".ico": "image/x-icon", ".woff2": "font/woff2" };

const walk = (dir) => readdirSync(dir).flatMap((f) => { const p = join(dir, f); return statSync(p).isDirectory() ? walk(p) : [p]; });
const files = {};
for (const p of walk(pub)) {
  const key = "/" + relative(pub, p).split("\\").join("/"), ext = extname(p).toLowerCase();
  if (BINARY[ext]) {
    const buf = readFileSync(p);
    files[key] = { type: BINARY[ext], hash: createHash("sha1").update(buf).digest("hex").slice(0, 16), b64: buf.toString("base64") };
    continue;
  }
  const type = TYPES[ext];
  if (!type) { console.warn(`skipped (unknown type): ${relative(root, p)}`); continue; }
  const body = await minify(readFileSync(p, "utf8"), ext);
  files[key] = { type, hash: createHash("sha1").update(body).digest("hex").slice(0, 16), body };
}
const worker = readFileSync(join(root, "src/worker.js"), "utf8");
const out = `// GENERATED by tools/build.mjs — edit public/ and src/worker.js instead\nconst FILES = ${JSON.stringify(files)};\n\n${worker}`;
mkdirSync(join(root, "dist"), { recursive: true });
writeFileSync(join(root, "dist/worker.js"), out);
console.log(`dist/worker.js  ${(out.length / 1024).toFixed(1)} KB  (${Object.keys(files).length} files: ${Object.keys(files).join(", ")})`);
